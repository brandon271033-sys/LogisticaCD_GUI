    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
               List<Producto> orden = new ArrayList<>();
        inventario.inOrden(orden);
        StringBuilder sb = new StringBuilder("--- Inventario ordenado ---\n");
        for (Producto p : orden) sb.append(p).append("\n");
        sb.append("Altura del árbol: ").append(inventario.altura());
        txtSalida.setText(sb.toString());
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
                try {
            int cod = Integer.parseInt(txtCodigo.getText().trim());
            Producto p = inventario.buscar(cod);
            txtSalida.setText(p != null ? "Encontrado: " + p : "No existe el producto.");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código inválido",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed
               try {
            int cod = Integer.parseInt(txtCodigo.getText().trim());
            String nom = txtNombre.getText().trim();
            int st = Integer.parseInt(txtStock.getText().trim());
            inventario.insertar(new Producto(cod, nom, st));
            txtSalida.setText("Producto insertado en el ABB.");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código y stock deben ser números",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnInsertarActionPerformed

